// builds docs/prototype/index.html, a single self-contained page that runs
// from disk (file://) or any static server, out of the verbatim sources in src/.
//
//   node docs/prototype/bundle.mjs           write index.html
//   node docs/prototype/bundle.mjs --check   fail if index.html is out of date

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const src = (name) => readFile(join(root, 'src', name), 'utf8');

const DATA_IMPORT = "import('./spammy-data.js')";
const COMPONENTS = ['Host', 'Show'];

/** json that is safe to place inside an inline <script> */
const inlineJson = (value) =>
  JSON.stringify(value).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

const build = async () => {
  const [page, runtime, data, ...components] = await Promise.all([
    src('The Spammy.dc.html'),
    src('support.js'),
    src('spammy-data.js'),
    ...COMPONENTS.map((name) => src(`${name}.dc.html`)),
  ]);

  if (!page.includes(DATA_IMPORT)) throw new Error(`expected ${DATA_IMPORT} in The Spammy.dc.html`);
  if (/<\/script/i.test(runtime)) throw new Error('support.js cannot be inlined: it contains </script');

  const runtimeTag = '<script src="./support.js"></script>';
  if (!page.includes(runtimeTag)) throw new Error(`expected ${runtimeTag} in The Spammy.dc.html`);

  // the runtime fetches sibling components from "./<Name>.dc.html" unless
  // window.__resources maps that url to a key in window.__resourceBlobs
  const resources = Object.fromEntries(COMPONENTS.map((name) => [`./${name}.dc.html`, `bundle:${name}.dc.html`]));
  const blobs = Object.fromEntries(COMPONENTS.map((name, i) => [`bundle:${name}.dc.html`, components[i]]));
  const dataUrl = `data:text/javascript;charset=utf-8;base64,${Buffer.from(data, 'utf8').toString('base64')}`;

  const boot = [
    '<script>',
    `window.__resources = ${inlineJson(resources)};`,
    `window.__resourceBlobs = Object.fromEntries(Object.entries(${inlineJson(blobs)}).map(([k, v]) => [k, new Blob([v], { type: 'text/html' })]));`,
    `window.__spammyData = ${inlineJson(dataUrl)};`,
    '</script>',
    `<script>\n${runtime}\n</script>`,
  ].join('\n');

  const banner = '<!-- generated by docs/prototype/bundle.mjs from docs/prototype/src; do not edit -->';

  return page
    .replace(/^<!DOCTYPE html>\n/i, (doctype) => `${doctype}${banner}\n`)
    .replace(runtimeTag, () => boot)
    .replace(DATA_IMPORT, 'import(window.__spammyData)');
};

const target = join(root, 'index.html');
const html = await build();

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== html) {
    console.error('docs/prototype/index.html is out of date; run: node docs/prototype/bundle.mjs');
    process.exit(1);
  }
  console.log('docs/prototype/index.html is up to date');
} else {
  await writeFile(target, html);
  console.log(`wrote ${target} (${Buffer.byteLength(html)} bytes)`);
}
